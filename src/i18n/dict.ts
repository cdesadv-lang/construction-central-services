function build(i: 0 | 1): Dict {
  const out: Dict = {};
  for (const [ns, entries] of Object.entries(P)) {
    out[ns] = {};
    for (const [k, v] of Object.entries(entries)) out[ns][k] = v[i];
  }
  return out;
}

export const DICTS: Record<Lang, Dict> = { ar: build(0), en: build(1) };

export function translate(lang: Lang, key: string, fallback?: string): string {
  const [ns, ...rest] = key.split(".");
  const k = rest.join(".");
  return DICTS[lang][ns]?.[k] ?? DICTS.en[ns]?.[k] ?? fallback ?? k;
}
